import pandas as pd

INPUT_PATH  = "med_calc_og.csv"
OUTPUT_PATH = "med_calc_extracted_numbered.csv"

df = pd.read_csv(INPUT_PATH)
print(df.shape)
print(df["Note Type"].value_counts(dropna=False))

df = df[df["Note Type"] == "Extracted"].reset_index(drop=True)
print(f"Rows kept: {len(df)}")

def number_lines(text):
    if pd.isna(text):
        return text
    # split on newlines, strip whitespace, drop empty lines
    lines = [ln.strip() for ln in str(text).split("\n") if ln.strip()]
    return "\n".join(f"{i}. {ln}" for i, ln in enumerate(lines, start=1))

df["Ground Truth Explanation"] = df["Ground Truth Explanation"].apply(number_lines)

print(df["Ground Truth Explanation"].iloc[0])

df.to_csv(OUTPUT_PATH, index=False, encoding="utf-8-sig")
print(f"Saved {len(df)} rows to {OUTPUT_PATH}")