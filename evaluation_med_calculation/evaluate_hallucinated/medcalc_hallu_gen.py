SYSTEM_PROMPT = """You are helping build a research benchmark that tests whether language models can detect hallucinations in Bangla medical reasoning. You are given a medical-calculator problem (in Bangla) with a correct step-by-step explanation. Inject exactly ONE hallucination of the requested type, at the step you are told.

Rules:
1. Rewrite the target step so it contains the requested hallucination type. The error must clearly belong to that type and not to another type.
2. Steps before the target step stay unchanged, so do not return them.
3. Return the target step and every later step, rewritten so the later steps follow consistently from the wrong step (the wrong value or fact propagates, including into the final answer). Never correct the error later.
4. Keep the original style, wording template, language (Bangla), digit script (Bangla digits as in the source), step numbering prefix, and Latin-script terms and units exactly as in the original.
5. Make the error plausible and subtle. Never add warnings, hedges, markers or any text that reveals the error.
6. Output a single JSON object only, with no markdown."""

def build_user_prompt(row, t, k):
    steps = [{"step": j + 1, "text": s} for j, s in enumerate(row["_steps"])]
    n = len(steps)
    return (f"Hallucination type to inject: {t} ({TYPE_NAME[t]})\nDefinition: {TYPE_DEF[t]}\nGuidance: {TYPE_HOW[t]}\n\n"
            f"Calculator: {row['Calculator Name']}\nQuestion: {row['Question']}\nPatient note: {row['Patient Note']}\n"
            f"Relevant entities (true values): {row['Relevant Entities']}\nCorrect final answer: {row['Ground Truth Answer']}\n\n"
            f"Correct explanation ({n} steps):\n{json.dumps(steps, ensure_ascii=False, indent=1)}\n\n"
            f"The hallucination MUST be in step {k + 1}. Return JSON with exactly these keys:\n"
            '{"modified_steps": [...], "description": "..."}\n'
            f"modified_steps = the rewritten steps {k + 1} through {n} (exactly {n - k} strings, each keeping its numbering prefix if the original has one). "
            "description = one English sentence: what was changed and why it is wrong.")

def call_llm(model, system, user, max_retries=4):
    headers = {"Authorization": f"Bearer {API_KEY}", "Content-Type": "application/json", "X-Title": "MedCalc-BN generation"}
    payload = {"model": model, "max_tokens": MAX_TOKENS, "response_format": {"type": "json_object"},
               "messages": [{"role": "system", "content": system}, {"role": "user", "content": user}]}
    last = ""
    for i in range(max_retries):
        try: r = requests.post(API_URL, headers=headers, json=payload, timeout=300)
        except requests.RequestException as e: last = str(e); time.sleep(2 ** i * 2); continue
        if r.status_code == 400 and "response_format" in payload: payload.pop("response_format"); continue
        if r.status_code in (429, 500, 502, 503, 504): last = str(r.status_code); time.sleep(2 ** i * 3); continue
        if not r.ok: raise RuntimeError(f"{r.status_code}: {r.text[:300]}")
        d = r.json()
        if "choices" not in d: last = str(d.get("error", ""))[:200]; time.sleep(2 ** i * 3); continue
        return d["choices"][0]["message"].get("content") or ""
    raise RuntimeError(f"API failed: {last}")

def parse_json(text):
    t = re.sub(r"^```(?:json)?\s*|\s*```$", "", text.strip())
    return json.loads(re.search(r"\{.*\}", t, re.S).group(0))

def fm(s): return re.sub(r"[^A-Za-z0-9+\-*/^=().]", "", body(s).translate(B2A))
def pnorm(m): return m.group(1).replace(" ", "").translate(B2A)

def tolerance(row):
    if row["_ok_ans"]: return fnum(row["Lower Limit"]), fnum(row["Upper Limit"]), "dataset limits"
    a = row["_ans"]
    if row["Output Type"] == "integer": return a, a, "extracted answer (exact)"
    return min(a * 0.95, a * 1.05), max(a * 0.95, a * 1.05), "extracted answer (+-5%)"

def validate(row, t, k, mod):
    S, n = row["_steps"], len(row["_steps"])
    if not (isinstance(mod, list) and len(mod) == n - k and all(isinstance(x, str) and x.strip() for x in mod)):
        return "bad modified_steps", None
    mod = [m.strip() for m in mod]
    for j, m in enumerate(mod):                                        # numbering prefix preserved (when the original has one)
        a, b = STEP_PREFIX.match(m), STEP_PREFIX.match(S[k + j])
        if b and (not a or pnorm(a) != pnorm(b)): return "numbering prefix changed", None
    if mod[0] == S[k]: return "target step unchanged", None
    if t == "A" and fm(mod[0]) == fm(S[k]): return "A: rule/formula not changed", None
    if t == "B":
        note = {float(x) for x in re.findall(r"\d+(?:\.\d+)?", row["Patient Note"].translate(B2A))}
        added, removed = nums(mod[0]) - nums(S[k]), nums(S[k]) - nums(mod[0])
        if not added or not removed or not any(a not in note for a in added): return "B: new value missing or present in note", None
    if t == "C":
        o, m = arith(S[k]), arith(mod[0])
        if not o or not m or re.sub(r"\s", "", o[0]) != re.sub(r"\s", "", m[0]): return "C: inputs changed or no arithmetic", None
        if m[2] == o[2] or abs(m[1] - m[2]) <= 0.02 * max(1, abs(m[1])): return "C: stated result not wrong", None
    new = last_answer(mod[-1])
    if new is None: return "no final answer found", None
    l, h, basis = tolerance(row)
    if l - 1e-9 <= new <= h + 1e-9: return "final answer still within tolerance", None
    return "ok", (mod, new, basis)

def attempt(i, t, att):
    row = df.loc[i]
    k = random.Random(f"{SEED}-{i}-{t}-{att}").choice(elig[t][i])      # deterministic per item
    try:
        raw = call_llm(GEN_MODEL, SYSTEM_PROMPT, build_user_prompt(row, t, k))
        obj = parse_json(raw); desc = str(obj.get("description", "")).strip()
        msg, out_ = validate(row, t, k, obj.get("modified_steps"))
    except Exception as e:
        raw, desc, msg, out_ = "", "", f"error: {e}", None
    return k, raw, desc, msg, out_

def work(i):
    row = df.loc[i]; S = row["_steps"]; logs = []; tries = 0
    for t in [assigned[i]] + [x for x in TYPES if x != assigned[i] and i in elig[x]]:   # fall back to other eligible types
        for att in range(ATTEMPTS_PER_TYPE):
            tries += 1
            k, raw, desc, msg, out_ = attempt(i, t, att)
            logs.append({"index": int(i), "type": t, "step": k + 1, "attempt": tries, "status": msg, "raw": raw})
            if msg == "ok":
                mod, new, basis = out_
                rec = {c: row[c] for c in df.columns if not c.startswith("_")}
                rec["Ground Truth Explanation"] = "\n".join(S)
                rec.update({
                    "Source Index": int(i), "Assigned Type": assigned[i],
                    "Hallucination Type": t, "Hallucination Type Name": TYPE_NAME[t],
                    "Hallucination Step": k + 1, "Original Step Text": S[k], "Hallucinated Step Text": mod[0],
                    "Hallucinated Explanation": "\n".join(S[:k] + mod),
                    "Hallucinated Answer": ("%g" % new).translate(A2B), "Answer Changed": True,
                    "Answer Check Basis": basis, "Hallucination Description": desc,
                    "Generator Model": GEN_MODEL, "Attempts": tries, "Validator Passed": True,
                    "Judge Sampled": False, "Judge Agrees": "", "Human Verified": "", "Reviewer Notes": ""})
                return rec, logs
    return None, logs

