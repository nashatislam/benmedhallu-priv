BN = "০১২৩৪৫৬৭৮৯"
B2A = str.maketrans(BN + "−×÷", "0123456789" + "-*/")
A2B = str.maketrans("0123456789", BN)
STEP_PREFIX = re.compile(r"^\s*([০-৯0-9]+\s*[.।])")

def split_steps(t): return [l.strip() for l in str(t).split("\n") if l.strip()]
def body(s): return re.sub(r"^\s*[০-৯0-9]+\s*[.।]\s*", "", s)
def nums(s): return {float(x) for x in re.findall(r"\d+(?:\.\d+)?", body(s).translate(B2A))}
def fnum(x): return float(str(x).translate(B2A))

ARI = re.compile(r"([\d.+\-*/^()\s]+)=\s*(-?\d+(?:\.\d+)?)")
def arith(step):
    """Last 'expression = result' in the step -> (expr, true_value, stated_result), else None."""
    t, out = body(step).translate(B2A), None
    for m in ARI.finditer(t):
        e = m.group(1).strip()
        if re.search(r"\d\s*[+\-*/^]\s*\(?\d", e) or re.search(r"\)\s*[*/+\-^]", e):
            try: out = (e, eval(e.replace("^", "**"), {"__builtins__": {}}), float(m.group(2)))
            except Exception: pass
    return out

def ent_nums(s):
    try: d = ast.literal_eval(s.translate(B2A))
    except Exception: return set()
    return {float(v[0]) for v in d.values() if isinstance(v, (list, tuple)) and v and isinstance(v[0], (int, float))}

def last_answer(step):
    t, best = body(step).translate(B2A), None
    for m in re.finditer(r"\d+(?:\.\d+)?", t):
        pre, post = t[:m.start()], t[m.end():]
        if pre.endswith("/") or re.match(r"\s*(m²|m2|m\^2)", post): continue
        neg = pre.endswith("-") and (len(pre) == 1 or pre[-2] in " =(")
        best = (-1 if neg else 1) * float(m.group())
    return best

