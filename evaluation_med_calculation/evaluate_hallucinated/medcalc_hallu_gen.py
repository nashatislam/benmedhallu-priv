def eligible_steps(row, t):
    S = row["_steps"]
    if t == "A": return [k for k, s in enumerate(S) if ("=" in s and re.search(r"[A-Za-z]", s)) or "পয়েন্ট" in s]
    if t == "B":
        en = ent_nums(row["Relevant Entities"]); return [k for k, s in enumerate(S) if k > 0 and nums(s) & en]
    r = [(k, arith(s)) for k, s in enumerate(S)]                       # C
    return [k for k, a in r if a and abs(a[1] - a[2]) <= 0.01 * max(1, abs(a[2]))]

